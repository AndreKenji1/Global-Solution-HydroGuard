CREATE TABLE ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(36) NOT NULL UNIQUE,
    versao BIGINT NOT NULL DEFAULT 0,
    descricao VARCHAR(1000) NOT NULL,
    endereco VARCHAR(180) NOT NULL,
    bairro VARCHAR(90),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ABERTA','EM_ANALISE','EM_ATENDIMENTO','RESOLVIDA')),
    prioridade VARCHAR(12) NOT NULL CHECK (prioridade IN ('BAIXA','MEDIA','ALTA')),
    categoria VARCHAR(80) NOT NULL,
    tipo_analise VARCHAR(32) NOT NULL,
    justificativa VARCHAR(500) NOT NULL,
    caminho_foto VARCHAR(120),
    tipo_foto VARCHAR(30),
    token_upload_hash VARCHAR(64),
    token_upload_expira_em TIMESTAMP WITH TIME ZONE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ocorrencias_status_prioridade_idx ON ocorrencias(status, prioridade);
CREATE INDEX ocorrencias_criado_em_idx ON ocorrencias(criado_em DESC, id DESC);
CREATE TABLE historico_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id BIGINT NOT NULL REFERENCES ocorrencias(id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ABERTA','EM_ANALISE','EM_ATENDIMENTO','RESOLVIDA')),
    autor VARCHAR(100) NOT NULL,
    alterado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX historico_status_ocorrencia_idx ON historico_status(ocorrencia_id, alterado_em, id);
